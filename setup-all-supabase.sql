create table if not exists public.kozak_friend_requests (
 id bigint generated by default as identity primary key,
 requester uuid not null references auth.users(id) on delete cascade,
 addressee uuid not null references auth.users(id) on delete cascade,
 status text not null default 'pending' check (status in ('pending','accepted')),
 created_at timestamptz not null default now(),
 constraint kozak_friend_not_self check (requester <> addressee),
 constraint kozak_friend_pair_unique unique (requester, addressee)
);
alter table public.kozak_friend_requests enable row level security;
drop policy if exists "Players can view their friend requests" on public.kozak_friend_requests;
create policy "Players can view their friend requests" on public.kozak_friend_requests for select to authenticated using ((select auth.uid()) = requester or (select auth.uid()) = addressee);
drop policy if exists "Players can send friend requests" on public.kozak_friend_requests;
create policy "Players can send friend requests" on public.kozak_friend_requests for insert to authenticated with check ((select auth.uid()) = requester and requester <> addressee and status = 'pending');
drop policy if exists "Recipients can accept friend requests" on public.kozak_friend_requests;
create policy "Recipients can accept friend requests" on public.kozak_friend_requests for update to authenticated using ((select auth.uid()) = addressee and status = 'pending') with check ((select auth.uid()) = addressee and status = 'accepted');
grant select, insert, update on public.kozak_friend_requests to authenticated;
grant usage, select on sequence public.kozak_friend_requests_id_seq to authenticated;

create or replace function public.kozak_protect_friend_request()
returns trigger language plpgsql security invoker set search_path = public
as $$
begin
 if auth.uid() is distinct from old.addressee
    or new.requester is distinct from old.requester
    or new.addressee is distinct from old.addressee
    or old.status <> 'pending'
    or new.status <> 'accepted' then
   raise exception 'Only the recipient can accept a pending friend request.';
 end if;
 return new;
end;
$$;
notify pgrst, 'reload schema';

drop trigger if exists kozak_friend_request_guard on public.kozak_friend_requests;
create trigger kozak_friend_request_guard
 before update on public.kozak_friend_requests
 for each row execute function public.kozak_protect_friend_request();



-- ==================== chat-schema.sql ====================

-- KH Kozak private chat between accepted friends.
-- Run this once in Supabase SQL Editor after community-schema.sql.
create table if not exists public.kozak_friend_messages (
 id bigint generated by default as identity primary key,
 sender_id uuid not null references auth.users(id) on delete cascade,
 recipient_id uuid not null references auth.users(id) on delete cascade,
 body text not null check (char_length(body) between 1 and 1200),
 created_at timestamptz not null default now(),
 constraint kozak_chat_not_self check (sender_id <> recipient_id)
);
create index if not exists kozak_friend_messages_pair_time_idx
 on public.kozak_friend_messages (sender_id, recipient_id, created_at desc);
create index if not exists kozak_friend_messages_recipient_time_idx
 on public.kozak_friend_messages (recipient_id, sender_id, created_at desc);
alter table public.kozak_friend_messages enable row level security;
drop policy if exists "Friends can read their private messages" on public.kozak_friend_messages;
create policy "Friends can read their private messages"
 on public.kozak_friend_messages for select to authenticated
 using (
   (auth.uid() = sender_id or auth.uid() = recipient_id)
   and exists (
     select 1 from public.kozak_friend_requests f
     where f.status = 'accepted'
       and ((f.requester = sender_id and f.addressee = recipient_id)
         or (f.requester = recipient_id and f.addressee = sender_id))
   )
 );
drop policy if exists "Friends can send private messages" on public.kozak_friend_messages;
create policy "Friends can send private messages"
 on public.kozak_friend_messages for insert to authenticated
 with check (
   auth.uid() = sender_id
   and sender_id <> recipient_id
   and char_length(body) between 1 and 1200
   and exists (
     select 1 from public.kozak_friend_requests f
     where f.status = 'accepted'
       and ((f.requester = sender_id and f.addressee = recipient_id)
         or (f.requester = recipient_id and f.addressee = sender_id))
   )
 );
grant select, insert on public.kozak_friend_messages to authenticated;
grant usage, select on sequence public.kozak_friend_messages_id_seq to authenticated;
notify pgrst, 'reload schema';



