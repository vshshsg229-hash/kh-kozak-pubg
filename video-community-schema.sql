-- Public player profile fields shared across devices. TikTok is a link, not OAuth.
create table if not exists public.kozak_player_profiles (
 user_id uuid primary key references auth.users(id) on delete cascade,
 nickname text not null default 'Гравець' check (char_length(nickname) between 2 and 24),
 tiktok_url text null check (tiktok_url is null or (char_length(tiktok_url) between 20 and 200 and tiktok_url ~ '^https://(www\\.)?tiktok\\.com/@[A-Za-z0-9._]{2,24}/?-- This stores public TikTok/YouTube/MP4 links, not uploaded video files.
create table if not exists public.kozak_shared_clips (
 id bigint generated by default as identity primary key,
 user_id uuid not null references auth.users(id) on delete cascade,
 nickname text not null default 'Гравець' check (char_length(nickname) between 2 and 24),
 title text not null check (char_length(title) between 2 and 90),
 caption text not null default '' check (char_length(caption) <= 300),
 video_url text not null check (char_length(video_url) between 8 and 500),
 created_at timestamptz not null default now()
);
create index if not exists kozak_shared_clips_created_idx on public.kozak_shared_clips(created_at desc);
alter table public.kozak_shared_clips enable row level security;
drop policy if exists "Players can view shared clips" on public.kozak_shared_clips;
create policy "Players can view shared clips" on public.kozak_shared_clips for select to authenticated using (true);
drop policy if exists "Players can publish their own clips" on public.kozak_shared_clips;
create policy "Players can publish their own clips" on public.kozak_shared_clips for insert to authenticated with check (auth.uid() = user_id and char_length(title) between 2 and 90 and char_length(caption) <= 300 and char_length(video_url) between 8 and 500);
drop policy if exists "Players can delete their own clips" on public.kozak_shared_clips;
create policy "Players can delete their own clips" on public.kozak_shared_clips for delete to authenticated using (auth.uid() = user_id);
grant select, insert, delete on public.kozak_shared_clips to authenticated;
grant usage, select on sequence public.kozak_shared_clips_id_seq to authenticated;

create table if not exists public.kozak_shared_clip_likes (
