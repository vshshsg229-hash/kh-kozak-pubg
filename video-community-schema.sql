-- KH Kozak shared short-video links. Run in Supabase SQL Editor.
-- This stores public TikTok/YouTube/MP4 links, not uploaded video files.
create table if not exists public.kozak_shared_clips (
 id bigint generated by default as identity primary key,
 user_id uuid not null references auth.users(id) on delete cascade,
 nickname text not null default 'Гравець' check (char_length(nickname) between 2 and 24),
 title text not null check (char_length(title) between 2 and 90),
 caption text not null default '' check (char_length(caption) <= 300),
 video_url text not null check (char_length(video_url) between 8 and 500),
 created_at timestamptz not null default now()
);
create index if not exists kozak_shared_clips_created_idx on public.kozak_shared_clips(created_at desc);
alter table public.kozak_shared_clips enable row level security;
drop policy if exists "Players can view shared clips" on public.kozak_shared_clips;
create policy "Players can view shared clips" on public.kozak_shared_clips for select to authenticated using (true);
drop policy if exists "Players can publish their own clips" on public.kozak_shared_clips;
create policy "Players can publish their own clips" on public.kozak_shared_clips for insert to authenticated with check (auth.uid() = user_id and char_length(title) between 2 and 90 and char_length(caption) <= 300 and char_length(video_url) between 8 and 500);
drop policy if exists "Players can delete their own clips" on public.kozak_shared_clips;
create policy "Players can delete their own clips" on public.kozak_shared_clips for delete to authenticated using (auth.uid() = user_id);
grant select, insert, delete on public.kozak_shared_clips to authenticated;
grant usage, select on sequence public.kozak_shared_clips_id_seq to authenticated;

create table if not exists public.kozak_shared_clip_likes (
 clip_id bigint not null references public.kozak_shared_clips(id) on delete cascade,
 user_id uuid not null references auth.users(id) on delete cascade,
 created_at timestamptz not null default now(),
 primary key (clip_id,user_id)
);
alter table public.kozak_shared_clip_likes enable row level security;
drop policy if exists "Players can view clip likes" on public.kozak_shared_clip_likes;
create policy "Players can view clip likes" on public.kozak_shared_clip_likes for select to authenticated using (true);
drop policy if exists "Players can like as themselves" on public.kozak_shared_clip_likes;
create policy "Players can like as themselves" on public.kozak_shared_clip_likes for insert to authenticated with check (auth.uid() = user_id);
drop policy if exists "Players can remove own clip likes" on public.kozak_shared_clip_likes;
create policy "Players can remove own clip likes" on public.kozak_shared_clip_likes for delete to authenticated using (auth.uid() = user_id);
grant select,insert,delete on public.kozak_shared_clip_likes to authenticated;

create table if not exists public.kozak_shared_clip_comments (
 id bigint generated by default as identity primary key,
 clip_id bigint not null references public.kozak_shared_clips(id) on delete cascade,
 user_id uuid not null references auth.users(id) on delete cascade,
 nickname text not null default 'Гравець' check (char_length(nickname) between 2 and 24),
 body text not null check (char_length(body) between 1 and 300),
 created_at timestamptz not null default now()
);
create index if not exists kozak_shared_clip_comments_idx on public.kozak_shared_clip_comments(clip_id,created_at asc);
alter table public.kozak_shared_clip_comments enable row level security;
drop policy if exists "Players can view clip comments" on public.kozak_shared_clip_comments;
create policy "Players can view clip comments" on public.kozak_shared_clip_comments for select to authenticated using (true);
drop policy if exists "Players can add own clip comments" on public.kozak_shared_clip_comments;
create policy "Players can add own clip comments" on public.kozak_shared_clip_comments for insert to authenticated with check (auth.uid() = user_id and char_length(body) between 1 and 300 and char_length(nickname) between 2 and 24);
grant select,insert on public.kozak_shared_clip_comments to authenticated;
notify pgrst, 'reload schema';
