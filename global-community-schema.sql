-- KH Kozak Gaming Hub 4.6 — global community feed and online presence
-- Run once in Supabase SQL Editor. Requires Anonymous Sign-Ins to be enabled.
create table if not exists public.kozak_community_posts (
 id bigint generated by default as identity primary key,
 user_id uuid not null references auth.users(id) on delete cascade,
 nickname text not null default 'Гравець' check (char_length(nickname) between 2 and 24),
 body text not null check (char_length(body) between 2 and 500),
 created_at timestamptz not null default now()
);
create index if not exists kozak_community_posts_created_idx on public.kozak_community_posts (created_at desc);
alter table public.kozak_community_posts enable row level security;
drop policy if exists "Community posts are visible to signed-in players" on public.kozak_community_posts;
create policy "Community posts are visible to signed-in players" on public.kozak_community_posts for select to authenticated using (true);
drop policy if exists "Players can publish community posts" on public.kozak_community_posts;
create policy "Players can publish community posts" on public.kozak_community_posts for insert to authenticated with check (auth.uid() = user_id and char_length(body) between 2 and 500 and char_length(nickname) between 2 and 24);
drop policy if exists "Players can delete their own community posts" on public.kozak_community_posts;
create policy "Players can delete their own community posts" on public.kozak_community_posts for delete to authenticated using (auth.uid() = user_id);
grant select, insert, delete on public.kozak_community_posts to authenticated;
grant usage, select on sequence public.kozak_community_posts_id_seq to authenticated;
create table if not exists public.kozak_presence (
 user_id uuid primary key references auth.users(id) on delete cascade,
 nickname text not null default 'Гравець' check (char_length(nickname) between 2 and 24),
 last_seen timestamptz not null default now()
);
alter table public.kozak_presence enable row level security;
drop policy if exists "Players can read recent community presence" on public.kozak_presence;
create policy "Players can read recent community presence" on public.kozak_presence for select to authenticated using (true);
drop policy if exists "Players can publish their own presence" on public.kozak_presence;
create policy "Players can publish their own presence" on public.kozak_presence for insert to authenticated with check (auth.uid() = user_id);
drop policy if exists "Players can update their own presence" on public.kozak_presence;
create policy "Players can update their own presence" on public.kozak_presence for update to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);
grant select, insert, update on public.kozak_presence to authenticated;
create table if not exists public.kozak_community_reactions (
 post_id bigint not null references public.kozak_community_posts(id) on delete cascade,
 user_id uuid not null references auth.users(id) on delete cascade,
 created_at timestamptz not null default now(),
 primary key (post_id, user_id)
);
alter table public.kozak_community_reactions enable row level security;
drop policy if exists "Signed-in players can read community reactions" on public.kozak_community_reactions;
create policy "Signed-in players can read community reactions" on public.kozak_community_reactions for select to authenticated using (true);
drop policy if exists "Players can react as themselves" on public.kozak_community_reactions;
create policy "Players can react as themselves" on public.kozak_community_reactions for insert to authenticated with check (auth.uid() = user_id);
drop policy if exists "Players can remove their own reactions" on public.kozak_community_reactions;
create policy "Players can remove their own reactions" on public.kozak_community_reactions for delete to authenticated using (auth.uid() = user_id);
grant select, insert, delete on public.kozak_community_reactions to authenticated;
notify pgrst, 'reload schema';
