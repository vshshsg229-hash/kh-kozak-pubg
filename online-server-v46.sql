-- KH么Kozak Gaming Hub 4.6 — shared online game server/lobby
-- Run once in the SAME Supabase project configured in supabase-config.js.
-- Requires Authentication > Sign-In Providers > Anonymous Sign-Ins enabled.

create table if not exists public.kozak_global_rooms (
  id bigint generated by default as identity primary key,
  owner_id uuid not null references auth.users(id) on delete cascade,
  owner_nickname text not null default 'Гравець' check (char_length(owner_nickname) between 2 and 24),
  room_name text not null check (char_length(room_name) between 2 and 60),
  game_mode text not null default 'PUBG Squad' check (char_length(game_mode) between 2 and 32),
  invite_url text not null default '' check (char_length(invite_url) <= 300),
  max_players integer not null default 4 check (max_players between 2 and 8),
  created_at timestamptz not null default now(),
  expires_at timestamptz not null default (now() + interval '24 hours')
);
create index if not exists kozak_global_rooms_active_idx on public.kozak_global_rooms (expires_at desc, created_at desc);
alter table public.kozak_global_rooms enable row level security;
drop policy if exists "Signed-in players can view active rooms" on public.kozak_global_rooms;
create policy "Signed-in players can view active rooms" on public.kozak_global_rooms for select to authenticated using (expires_at > now());
drop policy if exists "Players can create their own rooms" on public.kozak_global_rooms;
create policy "Players can create their own rooms" on public.kozak_global_rooms for insert to authenticated with check (auth.uid() = owner_id);
drop policy if exists "Players can update their own rooms" on public.kozak_global_rooms;
create policy "Players can update their own rooms" on public.kozak_global_rooms for update to authenticated using (auth.uid() = owner_id) with check (auth.uid() = owner_id);
drop policy if exists "Players can delete their own rooms" on public.kozak_global_rooms;
create policy "Players can delete their own rooms" on public.kozak_global_rooms for delete to authenticated using (auth.uid() = owner_id);
grant select, insert, update, delete on public.kozak_global_rooms to authenticated;
grant usage, select on sequence public.kozak_global_rooms_id_seq to authenticated;

create table if not exists public.kozak_global_room_members (
  room_id bigint not null references public.kozak_global_rooms(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  nickname text not null default 'Гравець' check (char_length(nickname) between 2 and 24),
  joined_at timestamptz not null default now(),
  primary key (room_id, user_id)
);
alter table public.kozak_global_room_members enable row level security;
drop policy if exists "Players can see lobby members" on public.kozak_global_room_members;
create policy "Players can see lobby members" on public.kozak_global_room_members for select to authenticated using (true);
drop policy if exists "Players can join a lobby as themselves" on public.kozak_global_room_members;
create policy "Players can join a lobby as themselves" on public.kozak_global_room_members for insert to authenticated with check (auth.uid() = user_id);
drop policy if exists "Players can leave their own lobby seat" on public.kozak_global_room_members;
create policy "Players can leave their own lobby seat" on public.kozak_global_room_members for delete to authenticated using (auth.uid() = user_id);
grant select, insert, delete on public.kozak_global_room_members to authenticated;

create table if not exists public.kozak_global_presence (
  user_id uuid primary key references auth.users(id) on delete cascade,
  nickname text not null default 'Гравець' check (char_length(nickname) between 2 and 24),
  current_area text not null default 'Gaming Hub' check (char_length(current_area) <= 40),
  last_seen timestamptz not null default now()
);
alter table public.kozak_global_presence enable row level security;
drop policy if exists "Players can see online presence" on public.kozak_global_presence;
create policy "Players can see online presence" on public.kozak_global_presence for select to authenticated using (true);
drop policy if exists "Players can publish their own presence" on public.kozak_global_presence;
create policy "Players can publish their own presence" on public.kozak_global_presence for insert to authenticated with check (auth.uid() = user_id);
drop policy if exists "Players can update their own presence" on public.kozak_global_presence;
create policy "Players can update their own presence" on public.kozak_global_presence for update to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);
grant select, insert, update on public.kozak_global_presence to authenticated;

notify pgrst, 'reload schema';
